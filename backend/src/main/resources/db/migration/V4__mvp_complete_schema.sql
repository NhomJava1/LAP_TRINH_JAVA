ALTER TABLE tenants
    ADD COLUMN IF NOT EXISTS email VARCHAR(255),
    ADD COLUMN IF NOT EXISTS phone VARCHAR(50),
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS app_users (
    id VARCHAR(64) PRIMARY KEY,
    tenant_id VARCHAR(64) REFERENCES tenants(id),
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tenant_rules (
    id VARCHAR(64) PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL UNIQUE REFERENCES tenants(id),
    earn_vnd_per_point BIGINT NOT NULL DEFAULT 1000,
    redeem_value_vnd_per_point BIGINT NOT NULL DEFAULT 10,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE api_keys
    ADD COLUMN IF NOT EXISTS name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS encrypted_secret TEXT,
    ADD COLUMN IF NOT EXISTS secret_iv VARCHAR(128),
    ADD COLUMN IF NOT EXISTS scopes VARCHAR(100) NOT NULL DEFAULT 'ISSUE,REDEEM,READ',
    ADD COLUMN IF NOT EXISTS revoked_at TIMESTAMP;

ALTER TABLE customer
    ALTER COLUMN id TYPE VARCHAR(192),
    ALTER COLUMN balance TYPE BIGINT;

ALTER TABLE customer
    ADD COLUMN IF NOT EXISTS external_customer_id VARCHAR(128);

CREATE UNIQUE INDEX IF NOT EXISTS idx_customer_tenant_ext
    ON customer (tenant_id, external_customer_id);

ALTER TABLE ledger_entries
    ADD COLUMN IF NOT EXISTS customer_id VARCHAR(128),
    ADD COLUMN IF NOT EXISTS amount_vnd BIGINT,
    ADD COLUMN IF NOT EXISTS chain_seq BIGINT;

ALTER TABLE idempotency_record
    ALTER COLUMN idempotency_key TYPE VARCHAR(255);

ALTER TABLE idempotency_record
    ADD COLUMN IF NOT EXISTS tenant_id VARCHAR(64);

ALTER TABLE outbox_events
    ADD COLUMN IF NOT EXISTS tenant_id VARCHAR(64),
    ADD COLUMN IF NOT EXISTS customer_id VARCHAR(128),
    ADD COLUMN IF NOT EXISTS settlement_mode VARCHAR(20) NOT NULL DEFAULT 'MOCK',
    ADD COLUMN IF NOT EXISTS tx_digest VARCHAR(128),
    ADD COLUMN IF NOT EXISTS retry_count INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS last_error TEXT,
    ADD COLUMN IF NOT EXISTS settled_at TIMESTAMP;

CREATE TABLE IF NOT EXISTS audit_logs (
    id VARCHAR(64) PRIMARY KEY,
    tenant_id VARCHAR(64),
    actor VARCHAR(255) NOT NULL,
    actor_role VARCHAR(50),
    action VARCHAR(100) NOT NULL,
    target_type VARCHAR(100),
    target_id VARCHAR(128),
    result VARCHAR(50) NOT NULL,
    details TEXT,
    correlation_id VARCHAR(64),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
